static FILE* g_log;

void klog(const char* fmt, ...)
{
	va_list ap;
	va_start(ap, fmt);
	if (g_log) { vfprintf(g_log, fmt, ap); fputc('\n', g_log); fflush(g_log); }
	va_end(ap);
}

/* pki.c logs through these */
enum wdi_log_level { WDI_LOG_LEVEL_DEBUG, WDI_LOG_LEVEL_INFO, WDI_LOG_LEVEL_WARNING, WDI_LOG_LEVEL_ERROR };
void wdi_log(enum wdi_log_level level, const char* function, const char* format, ...)
{
	va_list ap;
	(void)level;
	va_start(ap, format);
	if (g_log) { fprintf(g_log, "  [%s] ", function); vfprintf(g_log, format, ap); fputc('\n', g_log); fflush(g_log); }
	va_end(ap);
}
const char* wdi_windows_error_str(DWORD code)
{
	static char buf[256];
	DWORD err = code ? code : GetLastError();
	snprintf(buf, sizeof(buf), "[%#lx] ", err);
	FormatMessageA(FORMAT_MESSAGE_FROM_SYSTEM | FORMAT_MESSAGE_IGNORE_INSERTS, NULL, err,
	               MAKELANGID(LANG_ENGLISH, SUBLANG_DEFAULT), buf + strlen(buf), (DWORD)(sizeof(buf) - strlen(buf)), NULL);
	return buf;
}
