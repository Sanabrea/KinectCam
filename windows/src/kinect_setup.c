/*
 * KinectCam one-time Windows setup (runs elevated; one UAC prompt).
 *
 *   kinect_setup.exe --install   <KinectCam folder>  /i:UnityCaptureName=KinectCam
 *   kinect_setup.exe --uninstall <KinectCam folder>
 *
 * 1. Gives the Kinect v1's three USB devices (camera, motor, audio) Microsoft's
 *    built-in WinUSB driver, so libusb/libfreenect can talk to them. Same method
 *    as Zadig/libwdi (whose pki.c does the catalog + signing): a driver package
 *    (INF + catalog) is generated, signed with a freshly created local
 *    certificate whose private key is deleted right after signing, and
 *    installed. Only Microsoft's WinUSB.sys is used - no third-party kernel code.
 * 2. Registers the bundled Unity Capture DirectShow filter (MIT) as the
 *    virtual camera "KinectCam". It reads its name from this process's command
 *    line, which is why "/i:UnityCaptureName=KinectCam" is passed to us.
 *
 * --uninstall removes both and gives the Kinect back to Windows' own drivers.
 * Exit code: 0 ok, 1 driver failed, 2 camera failed, 3 both, 10 bad usage.
 */
